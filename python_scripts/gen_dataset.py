def write_mx3_file(path: Path, params: Dict[str, Any], max_time: float,
                   autosave_interval: float, tableautosave_interval: float,
                   gridsize=(100,100,1), cellsize=(2e-9,2e-9,1e-9)) -> None:
    """
    Write a MuMax3 script with TableAdd and autosave so we can monitor progress.
    (Function name and signature preserved.)
    """
    nx, ny, nz = gridsize
    dx, dy, dz = cellsize
    B = params.get("B_ext", [0.0,0.0,0.0])
    mx3 = f"""// Auto-generated by run_mumax_sweep.py
SetGridsize({nx},{ny},{nz})
SetCellsize({dx},{dy},{dz})
Msat = {params.get('Msat', 580e3)}
Aex = {params.get('Aex', 15e-12)}
alpha = {params.get('alpha', 0.8)}
Dind = {params.get('Dind', 3e-3)}
Ku1 = {params.get('Ku1', 5e5)}
anisU = vector(0,0,1)
B_ext = vector({B[0]},{B[1]},{B[2]})

// Table & autosave settings for monitoring
TableAdd(E_total)
TableAdd(MaxTorque)
tableautosave({tableautosave_interval})
autosave(m, {autosave_interval})

// random init & run
m = RandomMag()
run({max_time})
SaveAs(m, "final.ovf")
"""
    path.write_text(mx3)
    return


def read_table_last_entries(table_file: Path, nrows: int = 300) -> Optional[pd.DataFrame]:
    """
    Read table.txt into pandas returning last nrows, but:
      - if file missing or only contains comments / empty, return None quietly
      - if parsing fails for an unexpected reason, return None and log one succinct warning
    """
    if not table_file.exists():
        return None

    try:
        with table_file.open("r", encoding="utf-8", errors="ignore") as f:
            first_line = f.readline()
            if not first_line.startswith("#"):
                log(f"Unexpected file format in '{table_file}': no header line", level="WARN")
                return None
            # Remove leading "#" and extra spaces
            header_line = first_line.lstrip("# ").strip()
            # Split on *2 or more spaces* or tabs → preserves things like "t (s)"
            header = re.split(r'\s{2,}|\t+', header_line)

    except Exception as e:
        log(f"Could not read table file '{table_file}': {e}", level="WARN")
        return None

    try:
        df = pd.read_csv(
            table_file,
            comment="#",             # ignore comment lines
            delim_whitespace=True,   # whitespace-separated
            names=header,            # apply header we extracted
            header=None,             # don't auto-detect header
            engine="python",
            skiprows=1               # skip the first line (already used as header)
        )
        if df.shape[0] == 0:
            return None
        return df.tail(nrows)
    except Exception as e:
        log(f"Could not parse table file '{table_file}': {e}", level="WARN")
        return None

