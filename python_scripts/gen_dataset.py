def log(msg: str, level: str = "INFO", run_id: Optional[int] = None) -> None:
    """Nice timestamped log lines; include run_id when available."""
    t = time.strftime("%H:%M:%S")
    prefix = f"[{t}] {level}"
    if run_id is not None:
        prefix += f" (run {run_id})"
    print(f"{prefix}: {msg}")

