def start_image_gen():
    """
    Main driver — same name as original. Produces CSV log at `log_csv`.
    """
    results = []
    run_id = 0
    n_trials = 3

    log("Starting sweep", level="INFO")
    # iterate parameter grid exactly as your original script did
    for D in param_grid["Dind"]:
        for Ku1 in param_grid["Ku1"]:
            for B in param_grid["B_ext"]:
                for trial in range(n_trials):
                    run_id += 1
                    params = {
                        "Dind": D,
                        "Ku1": Ku1,
                        "Aex": param_grid["Aex"][0],
                        "alpha": param_grid["alpha"][0],
                        "B_ext": B,
                        "Msat": param_grid["Msat"][0],
                    }

                    run_dir = output_base / f"run_{run_id}"
                    run_dir.mkdir(exist_ok=True)
                    mx3_path = run_dir / f"run_{run_id}.mx3"

                    # write mx3 for this run
                    write_mx3_file(mx3_path, params, max_time,
                                   autosave_interval, tableautosave_interval,
                                   gridsize=gridsize, cellsize=cellsize)

                    log(f"Starting run (Dind={D}, Ku1={Ku1}, trial={trial}) -> {run_dir}", level="INFO", run_id=run_id)

                    # Launch mumax3 with its output dir set to run_dir
                    proc = subprocess.Popen(["mumax3", "-o", str(run_dir), str(mx3_path)],
                                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)

                    # Monitoring loop: poll table file while process runs
                    table_file = run_dir / "table.txt"
                    converged = False
                    cutoff = 1   # default assume cut off (did not converge before max_time)
                    stable_counter = 0
                    last_t = None
                    last_E = None
                    last_torque = None

                    try:
                        while True:
                            ret = proc.poll()
                            df = read_table_last_entries(table_file, nrows=200)
                            if df is not None and df.shape[0] > 0:
                                # find time/torque/energy columns (same heuristics you used)
                                time_col = df.columns[0]
                                torque_col = None
                                energy_col = None
                                for c in df.columns:
                                    cn = str(c).lower()
                                    if "torque" in cn:
                                        torque_col = c
                                    if "e_" in cn or "energy" in cn:
                                        energy_col = c
                                if torque_col is None:
                                    candidates = [c for c in df.columns if "max" in str(c).lower() and "torque" in str(c).lower()]
                                    torque_col = candidates[0] if candidates else None
                                if energy_col is None:
                                    candidates = [c for c in df.columns if "e_total" in str(c).lower() or "etotal" in str(c).lower()]
                                    energy_col = candidates[0] if candidates else None

                                last_row = df.iloc[-1]
                                try:
                                    last_t = float(last_row[time_col])
                                except Exception:
                                    try:
                                        last_t = float(df.index[-1])
                                    except Exception:
                                        last_t = last_t

                                if torque_col is not None:
                                    try:
                                        last_torque = float(last_row[torque_col])
                                    except Exception:
                                        last_torque = last_torque
                                if energy_col is not None:
                                    try:
                                        last_E = float(last_row[energy_col])
                                    except Exception:
                                        last_E = last_E

                                # convergence check using torque
                                if last_torque is not None:
                                    if last_torque < torque_tol:
                                        stable_counter += 1
                                    else:
                                        stable_counter = 0

                                    if stable_counter >= stable_checks:
                                        converged = True
                                        cutoff = 0
                                        log(f"Converged at t={last_t:.3e} s (MaxTorque={last_torque:.3e})", level="INFO", run_id=run_id)
                                        proc.terminate()
                                        try:
                                            proc.wait(timeout=5.0)
                                        except subprocess.TimeoutExpired:
                                            proc.kill()
                                        break

                            # if process finished naturally (reached end of mx3 script)
                            if ret is not None:
                                log(f"MuMax process exited with code {ret}", level="INFO", run_id=run_id)
                                break

                            # sleep between polls
                            time.sleep(poll_interval)

                    finally:
                        # ensure proc terminated
                        if proc.poll() is None:
                            proc.terminate()
                            try:
                                proc.wait(timeout=5.0)
                            except subprocess.TimeoutExpired:
                                proc.kill()

                        # capture stdout/stderr (optional, helps debugging)
                        try:
                            out, err = proc.communicate(timeout=0.1)
                        except Exception:
                            out, err = ("","")
                        if out:
                            (run_dir / "stdout.txt").write_text(out)
                        if err:
                            (run_dir / "stderr.txt").write_text(err)

